"""
Chess Game Results Analyzer

This script reads a CSV file (results.csv, generated by evaluate_duels.py)
containing chess game results and generates the outcomes, including win
counts for White and Black, the number of draws, and checkmate occurrences.

The input CSV file should have the following columns:
- 'game': A unique identifier for each chess game.
- 'white': The evaluation score for White at each move.
- 'black': The evaluation score for Black at each move.
- 'ply': The move notation, where a move ending in '#' indicates checkmate.

Usage:
Run this script directly.
"""

import pandas as pd


def analyze_chess_results(file_path):
    df = pd.read_csv(file_path)

    white_wins = 0
    black_wins = 0
    draws = 0
    white_checkmates = 0
    black_checkmates = 0

    games = df["game"].unique()

    for game_id in games:
        game_moves = df[df["game"] == game_id]
        final_position = game_moves.iloc[-1]
        white_score = final_position["white"]
        black_score = final_position["black"]
        final_move = final_position["ply"]

        if isinstance(final_move, str) and final_move.endswith("#"):
            assert (
                white_score == 10000 or black_score == 10000
            ), "Checkmate should result in a score of 10000"
            if white_score == 10000:
                white_checkmates += 1
            else:
                black_checkmates += 1

        if white_score > black_score:
            white_wins += 1
        elif white_score < black_score:
            black_wins += 1
        else:
            draws += 1

    print(f"Total games analyzed: {len(games)}")
    print(f"White wins: {white_wins}")
    print(f"Black wins: {black_wins}")
    print(f"Draws: {draws}")
    print(f"Games ending in white checkmate: {white_checkmates}")
    print(f"Games ending in black checkmate: {black_checkmates}")

    return {
        "total_games": len(games),
        "white_wins": white_wins,
        "black_wins": black_wins,
        "draws": draws,
        "white checkmate": white_checkmates,
        "black checkmate": black_checkmates,
    }


if __name__ == "__main__":
    results = analyze_chess_results("results.csv")
